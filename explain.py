"""종합 판단 카드와 신호를 쉬운 말로 풀어쓴다. 지금 화면의 실제 숫자를 넣어서 설명한다.
설명은 판단을 돕는 풀이이고 사고팔라는 결론을 내리지 않는다."""
VERSION = 1


def _w(x):
    return f"{x:,.0f}원"


def _need_level(need):
    if need is None:
        return ""
    if need >= 70:
        return "맞히기가 매우 어려운 구조"
    if need >= 60:
        return "불리한 구조"
    if need >= 52:
        return "다소 불리하지만 감당할 만한 구조"
    if need >= 45:
        return "균형에 가까운 구조"
    return "유리한 구조"


def card_blocks(c):
    """[(제목, 마크다운)] 목록."""
    out = []
    price, ret, up, base, ratio, need = c["price"], c.get("ret"), c.get("up"), c.get("base"), c.get("ratio"), c.get("need_win")
    ps, pm = c.get("pair_short"), c.get("pair_mid")
    down = abs(base["pct"]) if base else None

    # ---- 한 줄 요약
    if up is None or base is None or need is None:
        s = "근거가 부족해서 손익비를 계산하지 못했어요. 수급·컨센서스·안전 점검을 가져오면 더 정확해져요."
    else:
        s = f"보수적으로 보면 **오를 수 있는 폭은 약 +{up:.1f}%, 내려갈 수 있는 폭은 약 -{down:.1f}%**예요. "
        if up > 0:
            s += f"내려갈 폭이 오를 폭의 **약 {down / up:.1f}배**라서, 이 숫자만 보면 **{_need_level(need)}**예요(본전이 되려면 약 {need:.0f}%를 맞혀야 해요). "
        else:
            s += "오를 근거를 찾지 못해서 **구조적으로 불리**해요. "
        if ret is not None and ret >= 100:
            s += f"다만 이미 평단 대비 **+{ret:.0f}%**의 수익이 난 종목이라, 이 카드의 핵심 질문은 '더 오를까'보다 **'지금 있는 수익을 어떻게 지킬까'**예요."
        elif ret is not None and ret < 0:
            s += f"지금은 평단 대비 **{ret:.0f}%**의 손실 구간이라, 평단이 아니라 **지금 가격에서 새로 산다면 받아들일 수 있는 구조인지**를 보는 게 핵심이에요."
    out.append(("한 줄 요약", s))

    # ---- 상승 여력
    chosen = [u for u in c["ups"] if u["core"] and up is not None and abs(u["pct"] - up) < 1e-9]
    t = ("앞으로 오를 수 있는 폭을 **일부러 작게** 잡은 값이에요. 후보 중 ●로 표시된 것들 가운데 **가장 작은 값**을 써요.\n"
         "- **컨센서스 목표가의 절반**: 증권사 전망은 낙관적인 경향이 있어서 여력의 절반만 믿어요.\n"
         "- **가까운 저항선**: 과거에 가격이 막혔던 위쪽 가격대예요.\n")
    if chosen:
        u = chosen[0]
        t += f"\n이번 기준은 **{u['label']}**(약 {_w(u['price'])}, {u['pct']:+.1f}%)이에요. {u['note']}."
        if "저항선" in u["label"]:
            t += ("\n\n⚠ 가까운 저항선은 '여기가 끝'이라는 뜻이 아니라 '여기서 한 번 막힐 수 있다'는 뜻이에요. 저항을 넘으면 더 오를 수 있어서, "
                  "최근 고점 바로 아래에서는 상승 여력이 **실제보다 작게** 계산될 수 있어요.")
    else:
        t += "\n이번에는 기준으로 쓸 후보를 찾지 못했어요."
    out.append(("보수적 상승 여력", t))

    # ---- 하락 위험
    t = ("내려갈 수 있는 폭을 **넉넉하게** 잡은 값이에요. 단기·중기·극단 세 단계를 보고, 손익비에는 **중기**를 써요.\n"
         "- **단기**: 가까운 지지선(과거에 내렸다가 반등한 가격대)\n"
         "- **중기**: 그 아래 지지선, 또는 이 종목이 과거 큰 조정에서 밀렸던 수준\n"
         "- **극단**: 최근 1년 최저 종가\n")
    if base:
        t += f"\n이번 기준은 **{base['label']}**(약 {_w(base['price'])}, {base['pct']:.1f}%)이에요."
        extra = [f"{d['term']} {d['pct']:.1f}%" for d in c["downs"] if d is not base]
        if extra:
            t += " 다른 후보: " + ", ".join(extra) + "."
        t += "\n\n내려간다는 말이 **반드시 거기까지 간다**는 뜻은 아니에요. '최악에 가까운 경우 이 정도까지 열려 있다'는 지도예요."
    out.append(("하락 위험", t))

    # ---- 손익비
    if ratio is not None and up is not None and down:
        t = (f"**{ratio:.2f} = 오를 폭 {up:.1f}% ÷ 내릴 폭 {down:.1f}%**예요. 1이면 오를 폭과 내릴 폭이 같고, 1보다 작으면 내릴 폭이 더 커요. "
             f"1.2 이상이면 보통, 2 이상이면 유리하다고 봐요.\n\n등급은 **{c['grade']}**이에요.")
        if ps or pm:
            t += "\n\n**기간을 맞춰서 보면** 이렇게 달라질 수 있어요(위 '기간별 손익비' 표와 같아요).\n"
            if ps:
                t += f"- 단기(가까운 저항선 vs 가까운 지지선): 오를 {ps['up']:+.1f}% / 내릴 -{ps['down']:.1f}% → 손익비 {ps['ratio']:.2f}, 필요 승률 {ps['need']:.0f}%\n"
            if pm:
                t += f"- 중기(컨센서스 절반 vs 중기 하락): 오를 {pm['up']:+.1f}% / 내릴 -{pm['down']:.1f}% → 손익비 {pm['ratio']:.2f}, 필요 승률 {pm['need']:.0f}%\n"
            t += "맨 위 손익비는 이 중 가장 보수적인 조합이라, 실제 판단에는 기간별 숫자를 같이 보세요."
    else:
        t = "손익비를 계산하려면 오를 근거와 내려갈 근거가 모두 필요해요."
    out.append(("손익비", t))

    # ---- 필요 승률
    if need is not None and up is not None and down:
        t = (f"이 손익비로 **같은 판단을 여러 번 반복**한다고 할 때, **본전이 되려면 맞혀야 하는 비율**이에요.\n\n"
             f"계산: 내릴 폭 ÷ (오를 폭 + 내릴 폭) = {down:.1f} ÷ ({up:.1f} + {down:.1f}) = **{need:.0f}%**\n\n"
             f"쉽게 말하면 같은 판단을 10번 하면 **{need / 10:.1f}번 이상** 맞아야 손해가 안 나는 구조예요.\n\n"
             f"읽는 기준: 50% 안팎이면 균형, 60%를 넘으면 불리, 70%를 넘으면 맞히기 매우 어려운 구조예요. 51~55%를 꾸준히 맞히는 것도 쉽지 않다고 알려져 있어서, "
             f"이번 {need:.0f}%는 **{_need_level(need)}**로 볼 수 있어요.\n\n"
             "주의: 오르면 정확히 상승 여력만큼, 내리면 정확히 하락 위험만큼 변한다는 **단순한 가정**이에요. 실제로는 그 사이에서 끝나는 경우가 대부분이에요.")
    else:
        t = "필요 승률을 계산하려면 손익비가 필요해요."
    out.append(("필요 승률", t))

    # ---- 근거 충족도
    miss = [n for n, v in c["have"].items() if not v]
    t = (f"카드를 만들 때 쓴 근거 4가지(가격 흐름, 컨센서스, 수급, 안전·재무) 중 **{c['n_have']}개**를 반영했어요. ")
    t += ("모두 반영돼서 숫자의 근거는 충분한 편이에요(근거가 충분한 것과 숫자가 맞는 것은 다른 이야기예요)." if not miss else
          f"**{', '.join(miss)}**가 빠져 있어요. 내 자산 탭의 수급·컨센서스 가져오기, 안전 점검 탭의 재무 가져오기로 채울 수 있어요.")
    out.append(("근거 충족도", t))

    # ---- 경고 풀이
    if c["warns"]:
        out.append(("위 경고의 뜻", "\n".join(f"- {w_explain(w)}" for w in c["warns"])))

    # ---- 시나리오 표
    sc = c.get("scen") or []
    if sc:
        lines = []
        for r in sc:
            avg_part = ""
            if r["내 평단 대비(%)"] == r["내 평단 대비(%)"]:
                avg_part = f"내 평단 대비 **{r['내 평단 대비(%)']:+.0f}%**" + (" — 아직 평단보다 높아서 수익은 남아요" if r["내 평단 대비(%)"] > 0 else " — 평단보다 낮아서 손실 구간이에요")
            tot = f", 총자산이 **{r['총자산 영향(%)']:+.2f}%** 변해요" if r["총자산 영향(%)"] == r["총자산 영향(%)"] else ""
            lines.append(f"- **{r['시나리오']}**(약 {_w(r['가격'])}, 현재가 대비 {r['현재가 대비(%)']:+.0f}%)이 되면: {avg_part}{tot}.")
        out.append(("내 평단 기준 시나리오 읽는 법", "각 가격이 되었을 때 **내 계좌에서 일어나는 일**이에요. '내 평단 대비'는 그 가격이 내 평균 매수단가보다 얼마나 높은지, '총자산 영향'은 보유 전체 자산이 몇 % 변하는지예요.\n\n" + "\n".join(lines)))

    # ---- 질문
    if ret is not None and ret >= 30:
        q = ("이미 큰 수익이 난 종목이에요. 아래 세 가지를 스스로 물어보세요.\n"
             "1. 지금 이 가격에서 **새로 산다면** 이 손익비를 받아들일까?\n"
             "2. 이익 일부를 확정한다면, 남는 수량의 **보호선과 무효가격**은 어디에 둘까?\n"
             "3. 지금 들고 있는 **이유**(처음 산 이유)가 아직 유효한가?")
    elif ret is not None and ret < 0:
        q = ("손실 구간인 종목이에요. 아래를 스스로 물어보세요.\n"
             "1. **평단은 시장이 신경 쓰지 않아요.** 지금 가격에서 새로 산다면 살까?\n"
             "2. 다시 믿을 수 있는 **회복 조건**(실적, 수급, 가격 흐름)은 무엇이고, 그게 안 보이면 어디까지 **손실을 허용**할까?\n"
             "3. 처음 산 이유가 아직 유효한가, 바뀌었다면 꼬리표(중장기·스윙)도 바꿔야 하지 않나?")
    else:
        q = ("1. 지금 가격에서 새로 산다면 이 손익비가 괜찮을까?\n2. 틀렸다고 인정할 **무효가격**은 어디인가?\n3. 이 판단의 이유는 무엇인가?")
    out.append(("이 카드로 생각해 볼 질문", q + "\n\n답은 아래 **판단 기록**에 한 줄로 남겨두면, 나중에 결과와 비교할 수 있어요."))

    # ---- 한계
    out.append(("이 카드의 한계", "- 예측이 아니라 **지금 가진 근거로 잡은 보수적인 범위**예요. 맞힐 확률은 아직 검증되지 않아서 모른다고 보고 '필요 승률'만 보여줘요.\n"
                                  "- 상승은 가까운 저항선·컨센서스 절반, 하락은 지지선·과거 되돌림이라 **내려갈 쪽을 더 넉넉하게** 잡아요. 손익비가 낮게 나오는 방향으로 치우쳐 있어요.\n"
                                  "- 뉴스·공시 이벤트, 시장 전체 흐름(금리·환율·지수)은 아직 숫자에 반영하지 못했어요.\n"
                                  "- 판단 기록이 쌓이면 이 카드의 등급이 실제로 도움이 됐는지 확인할 수 있어요."))
    return out


def w_explain(w):
    if "손절선" in w or "점검선" in w:
        return w + " → 처음 정한 기준을 넘어 들고 있다는 뜻이에요. 기준을 바꿨다면 이유를 기록해 두는 게 좋아요."
    if "안전 기준" in w:
        return w + " → 재무·공시상 약한 고리가 있다는 뜻이에요. 안전 점검 탭에서 어떤 항목인지 확인하세요."
    if "외국인·기관이 함께 순매도" in w:
        return w + " → 큰 투자자가 단기적으로 팔고 있다는 뜻이에요. 오른 종목에서는 이익 실현일 수도 있고, 이후 흐름은 보장되지 않아요. 며칠 더 이어지는지 보세요."
    if "상승 여력이 0" in w:
        return w + " → 컨센서스가 현재가 이하이거나 위쪽에 근거가 없다는 뜻이에요."
    return w


